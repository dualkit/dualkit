// Counts every test in the monorepo and writes lib/v3/testcount.ts. Run: node scripts/count-tests.mjs
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..', '..', '..')
const OUT = resolve(HERE, '..', 'lib', 'v3', 'testcount.ts')

/** Sums numTotalTests over vitest JSON reports. */
export const sumTests = (reports) => reports.reduce((n, r) => n + (Number.isInteger(r?.numTotalTests) ? r.numTotalTests : 0), 0)

const workspaces = () => ['packages', 'apps'].flatMap((g) => readdirSync(join(ROOT, g)).map((d) => join(ROOT, g, d)))
  .filter((dir) => existsSync(join(dir, 'package.json')) && (existsSync(join(dir, 'test')) || existsSync(join(dir, 'src'))))

function report(dir) {
  const out = execFileSync('npx', ['vitest', 'run', '--reporter=json', '--passWithNoTests'], { cwd: dir, encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] })
  return JSON.parse(out.slice(out.indexOf('{')))
}

const render = (n) => `// Generated by scripts/count-tests.mjs. Do not edit; run \`node scripts/count-tests.mjs\` to refresh.\nexport const TEST_COUNT = ${n}\n`

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const reports = workspaces().map((dir) => {
    try { return report(dir) } catch (e) { if (e.stdout) return JSON.parse(String(e.stdout).slice(String(e.stdout).indexOf('{'))); throw e }
  })
  const total = sumTests(reports)
  writeFileSync(OUT, render(total))
  console.log(total)
}
