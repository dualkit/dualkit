import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import type { BenchModel, BenchMonth } from '../lib/bench-schema'
import { benchRows } from '../lib/v3/bench-rows'
import { V3 } from '../lib/v3/copy'
import { numbersStats, skillCount } from '../lib/v3/numbers'
import { TEST_COUNT } from '../lib/v3/testcount'
// @ts-expect-error plain .mjs script with no types
import { sumTests } from '../scripts/count-tests.mjs'

const model = (id: string, rank: number | null, alone: number | null, dualkit: number | null): BenchModel => ({
  id, label: `Model ${id}`, provider: 'openrouter', by: 'Maker', mark: 'google', rank, previousRank: null, move: null, isNew: true,
  alone: alone === null ? null : { rulesPassed: alone, outOf: 100, score: alone },
  dualkit: dualkit === null ? null : { rulesPassed: dualkit, outOf: 100, score: dualkit },
  lift: alone === null || dualkit === null ? null : dualkit - alone, screens: [],
})
const month = (models: BenchModel[]): BenchMonth => ({ month: '2026-11', generatedAt: '2026-11-01T00:00:00Z', ruleCount: 20, models })

describe('benchRows', () => {
  it('uses the four sample rows from the copy when no month exists', () => {
    const { rows, sample } = benchRows(null)
    expect(sample).toBe(true)
    expect(rows).toHaveLength(4)
    expect(rows.map((r) => [r.name, r.maker, r.alone, r.dualkit])).toEqual(V3.bench.rows.map((r) => [...r]))
  })

  it('takes the top four ranked models of a real month', () => {
    const m = month([model('f', 6, 10, 20), model('b', 2, 50, 80), model('a', 1, 60, 90), model('e', null, null, null), model('c', 3, 40, 70), model('d', 4, 30, 60), model('g', 5, 20, 40)])
    const { rows, sample } = benchRows(m)
    expect(sample).toBe(false)
    expect(rows.map((r) => r.name)).toEqual(['Model a', 'Model b', 'Model c', 'Model d'])
    expect(rows[0]).toEqual({ name: 'Model a', maker: 'google', alone: 60, dualkit: 90 })
  })

  it('falls back to the sample when a month has no model with both points', () => {
    expect(benchRows(month([model('a', null, null, null)])).sample).toBe(true)
  })
})

describe('TEST_COUNT', () => {
  it('is a positive integer', () => {
    expect(Number.isInteger(TEST_COUNT)).toBe(true)
    expect(TEST_COUNT).toBeGreaterThan(0)
  })

  it('is the generated file the script writes, with its header comment', () => {
    const text = readFileSync(join(__dirname, '..', 'lib', 'v3', 'testcount.ts'), 'utf8')
    expect(text.startsWith('// Generated by scripts/count-tests.mjs')).toBe(true)
    expect(Number(/TEST_COUNT = (\d+)/.exec(text)?.[1])).toBe(TEST_COUNT)
  })

  it('sums numTotalTests the way the script prints it', () => {
    expect(sumTests([{ numTotalTests: 10 }, { numTotalTests: 5 }, {}])).toBe(15)
  })
})

describe('numbersStats', () => {
  it('reads each counter from its source and labels it from the copy', () => {
    const stats = numbersStats()
    expect(stats.map((s) => s.what)).toEqual(V3.numbers.stats.map((s) => s[1]))
    expect(stats[0]?.value).toBe(TEST_COUNT.toLocaleString('en-US'))
    expect(stats.slice(1).map((s) => s.value)).toEqual(['20', '6', String(skillCount())])
  })

  it('counts the plugin skill directories', () => {
    expect(skillCount()).toBe(4)
  })
})
